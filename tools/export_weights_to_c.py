"""Convert a trained PyTorch DQN state_dict (.pt) into a C header for the
on-device inference sketches.

The header holds one weight matrix and one bias vector per Linear layer as
flat float arrays (PyTorch layout: W is [out_dim, in_dim], row-major), marked
PROGMEM_ATTR so the sketches can keep them in flash.

Usage (from the repository root):
    python tools/export_weights_to_c.py <weights.pt> <output.h> <name_prefix>

Examples:
    python tools/export_weights_to_c.py src/cartpole/pc/weights/cartpole_dqn.pt cartpole_dqn_weights.h cartpole
    python tools/export_weights_to_c.py src/grid/pc/weights/grid_dqn_n30.pt grid_dqn_weights.h grid

Copy the generated header into the sketch folder (inference and demo sketches
each need their own copy).
"""

import sys

import torch


def load_layers(pt_path):
    """Return [(W, b), ...] for the Linear layers of a QNetwork state_dict.

    QNetwork wraps an nn.Sequential called "net" (Linear, ReLU, Linear, ...),
    so parameter keys are net.0.*, net.2.*, net.4.*, ... (ReLU has none).
    """
    state = torch.load(pt_path, map_location="cpu")

    layers = []
    idx = 0
    while f"net.{idx}.weight" in state:
        layers.append((state[f"net.{idx}.weight"].numpy(),
                       state[f"net.{idx}.bias"].numpy()))
        idx += 2

    if not layers:
        raise RuntimeError(f"no net.N.weight keys found in {pt_path}; "
                           "is this a QNetwork state_dict from train_dqn.py?")
    return layers


def write_header(layers, header_path, source_path, name):
    with open(header_path, "w") as f:
        f.write("// Auto-generated by export_weights_to_c.py -- do not edit by hand.\n")
        f.write(f"// Source: {source_path}\n")
        f.write("#pragma once\n\n")
        f.write(f"const int {name}_n_layers = {len(layers)};\n\n")

        for i, (W, b) in enumerate(layers):
            out_dim, in_dim = W.shape
            f.write(f"const int {name}_layer{i}_in = {in_dim};\n")
            f.write(f"const int {name}_layer{i}_out = {out_dim};\n")
            f.write(f"const float {name}_layer{i}_W[{out_dim * in_dim}] PROGMEM_ATTR = {{\n")
            f.write(",".join(f"{v:.8f}f" for v in W.flatten()))
            f.write("\n};\n")
            f.write(f"const float {name}_layer{i}_b[{out_dim}] PROGMEM_ATTR = {{\n")
            f.write(",".join(f"{v:.8f}f" for v in b))
            f.write("\n};\n\n")


def export(pt_path, header_path, name):
    layers = load_layers(pt_path)
    write_header(layers, header_path, pt_path, name)

    total_params = sum(W.size + b.size for W, b in layers)
    print(f"wrote {header_path}: {len(layers)} layers, {total_params} parameters "
          f"(~{total_params * 4} bytes as float32)")
    for i, (W, _) in enumerate(layers):
        activation = "ReLU" if i < len(layers) - 1 else "none (raw Q-values)"
        print(f"  layer {i}: {W.shape[1]} -> {W.shape[0]}  ({activation})")


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    export(sys.argv[1], sys.argv[2], sys.argv[3])


if __name__ == "__main__":
    main()
